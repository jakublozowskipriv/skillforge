"""Offline support for the static site: a precaching service worker and a web app manifest.

Generated after `mkdocs build` from the actual output files, so the worker precaches exactly what
was built. The cache name contains a content hash: any change to the site installs a fresh cache
and drops the old one on activation.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

PRECACHE_SUFFIXES = {".html", ".css", ".js", ".json", ".svg", ".png", ".woff2", ".webmanifest"}
EXCLUDED = {"sw.js", "sitemap.xml", "sitemap.xml.gz"}

SW_TEMPLATE = """\
// Generated by skillforge.site.offline — do not edit.
const CACHE = "skillforge-__VERSION__";
const PRECACHE = __FILES__;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Cache first (the site is static and versioned by CACHE), network as fallback;
// for page navigations without network fall back to the cached page or the home page.
self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).catch(() =>
        req.mode === "navigate"
          ? caches.match(new URL("./", self.location).href)
          : Response.error()
      );
    })
  );
});
"""


def precache_list(site_dir: Path) -> list[str]:
    """URLs relative to the worker (site root), with directory URLs for ``index.html`` pages."""
    urls: list[str] = []
    for path in sorted(site_dir.rglob("*")):
        if not path.is_file() or path.name in EXCLUDED or path.suffix not in PRECACHE_SUFFIXES:
            continue
        rel = path.relative_to(site_dir).as_posix()
        if rel == "index.html":
            urls.append("./")
        elif rel.endswith("/index.html"):
            urls.append(rel.removesuffix("index.html"))
        urls.append(rel)
    return urls


def site_version(site_dir: Path, files: list[str]) -> str:
    digest = hashlib.sha256()
    for rel in files:
        path = site_dir / rel
        if path.is_file():
            digest.update(rel.encode())
            digest.update(path.read_bytes())
    return digest.hexdigest()[:12]


def write_service_worker(site_dir: Path) -> Path:
    files = precache_list(site_dir)
    worker = SW_TEMPLATE.replace("__VERSION__", site_version(site_dir, files)).replace(
        "__FILES__", json.dumps(files, indent=2)
    )
    target = site_dir / "sw.js"
    target.write_text(worker, encoding="utf-8")
    return target


def manifest(name: str, start_url: str = "./") -> dict[str, object]:
    return {
        "name": name,
        "short_name": "skillforge",
        "start_url": start_url,
        "scope": "./",
        "display": "standalone",
        "background_color": "#ffffff",
        "theme_color": "#3f51b5",
        "lang": "pl",
        "icons": [
            {"src": "assets/icon.svg", "sizes": "any", "type": "image/svg+xml"},
            {"src": "assets/icon-192.png", "sizes": "192x192", "type": "image/png"},
            {"src": "assets/icon-512.png", "sizes": "512x512", "type": "image/png"},
        ],
    }
